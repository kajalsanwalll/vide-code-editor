
import { NextRequest, NextResponse } from "next/server";

interface ChatMessage {
  role: "user" | "assistant";
  content: string;
}

interface ChatRequest {
  message: string;
  history: ChatMessage[];
}

class GeminiApiError extends Error {
  status: number;

  constructor(message: string, status: number) {
    super(message);
    this.name = "GeminiApiError";
    this.status = status;
  }
}

const sleep = (ms: number) =>
  new Promise((resolve) => setTimeout(resolve, ms));

async function generateAIResponse(
  messages: ChatMessage[]
): Promise<string> {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    throw new GeminiApiError(
      "GEMINI_API_KEY is not configured",
      500
    );
  }

  const systemPrompt = `You are Vide, a helpful AI coding assistant integrated into Vide Code Editor.

You help developers with:
- Code explanations and debugging
- Best practices and architecture advice
- Writing clean, efficient code
- Troubleshooting errors
- Code reviews and optimizations
- Frontend and backend development
- JavaScript, TypeScript, Python, C++, and other programming languages

Instructions:
- Provide clear, practical answers.
- Use Markdown formatting and code blocks when appropriate.
- Explain complex concepts in a beginner-friendly manner.
- When fixing code, provide working solutions and explain important changes.
- Be concise when the question is simple and detailed when necessary.
- When asked to generate code, provide complete usable code when appropriate.
- Be friendly, professional, and helpful.`;

  const contents = messages.map((msg) => ({
    role: msg.role === "assistant" ? "model" : "user",
    parts: [{ text: msg.content }],
  }));

  const maxAttempts = 3;

  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    try {
      console.log(
        `[GEMINI CHAT] Request attempt ${attempt}/${maxAttempts}`
      );

      const response = await fetch(
        "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent",
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            "x-goog-api-key": apiKey,
          },
          body: JSON.stringify({
            systemInstruction: {
              parts: [{ text: systemPrompt }],
            },
            contents,
            generationConfig: {
              temperature: 0.7,
              maxOutputTokens: 2048,
              topP: 0.9,
            },
          }),
          signal: AbortSignal.timeout(30000),
        }
      );

      const data = await response.json();

      if (!response.ok) {
        const errorMessage =
          data.error?.message || "Gemini API request failed";

        const retryable =
          response.status === 429 ||
          [500, 502, 503, 504].includes(response.status);

        console.error("[GEMINI API ERROR]", {
          status: response.status,
          message: errorMessage,
          attempt,
        });

        if (!retryable || attempt === maxAttempts) {
          throw new GeminiApiError(
            errorMessage,
            response.status
          );
        }

        const retryAfter = Number(
          response.headers.get("Retry-After")
        );

        const delay = Number.isFinite(retryAfter) &&
          retryAfter > 0
          ? Math.min(retryAfter * 1000, 10000)
          : attempt * 1000;

        console.log(
          `[GEMINI CHAT] Retrying in ${delay}ms...`
        );

        await sleep(delay);
        continue;
      }

      const aiResponse =
        data.candidates?.[0]?.content?.parts
          ?.map((part: { text?: string }) => part.text || "")
          .join("") || "";

      if (!aiResponse.trim()) {
        throw new GeminiApiError(
          "No response generated by Gemini",
          502
        );
      }

      console.log("[GEMINI CHAT] Response generated successfully");

      return aiResponse.trim();

    } catch (error) {
      const isNetworkError =
        error instanceof TypeError ||
        (error instanceof Error && error.name === "TimeoutError");

      const retryable =
        isNetworkError ||
        (error instanceof GeminiApiError &&
          [429, 500, 502, 503, 504].includes(error.status));

      console.error("[GEMINI CHAT] Generation error:", error);

      if (!retryable || attempt === maxAttempts) {
        if (error instanceof GeminiApiError) {
          throw error;
        }

        throw new GeminiApiError(
          error instanceof Error
            ? error.message
            : "Failed to generate AI response",
          isNetworkError ? 503 : 500
        );
      }

      const delay = attempt * 1000;

      console.log(
        `[GEMINI CHAT] Retrying after ${delay}ms...`
      );

      await sleep(delay);
    }
  }

  throw new GeminiApiError(
    "Gemini is temporarily unavailable. Please try again.",
    503
  );
}

export async function POST(req: NextRequest) {
  try {
    const body: ChatRequest = await req.json();

    const { message, history = [] } = body;

    if (!message || typeof message !== "string") {
      return NextResponse.json(
        {
          error: "Message is required and must be a string",
        },
        { status: 400 }
      );
    }

    const validHistory = Array.isArray(history)
      ? history.filter(
          (msg) =>
            msg &&
            typeof msg === "object" &&
            typeof msg.role === "string" &&
            typeof msg.content === "string" &&
            ["user", "assistant"].includes(msg.role)
        )
      : [];

    const recentHistory = validHistory.slice(-10);

    const messages: ChatMessage[] = [
      ...recentHistory,
      { role: "user", content: message },
    ];

    const aiResponse = await generateAIResponse(messages);

    return NextResponse.json({
      response: aiResponse,
      timestamp: new Date().toISOString(),
    });

  } catch (error) {
    console.error("[CHAT API ERROR]", error);

    const status =
      error instanceof GeminiApiError
        ? error.status
        : 500;

    const errorMessage =
      error instanceof Error
        ? error.message
        : "Unknown error";

    return NextResponse.json(
      {
        error: "Failed to generate AI response",
        details: errorMessage,
        retryable: [429, 500, 502, 503, 504].includes(status),
        timestamp: new Date().toISOString(),
      },
      { status }
    );
  }
}
